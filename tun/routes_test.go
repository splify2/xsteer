package tun

import "testing"

func TestEndpointCovered(t *testing.T) {
	hub := []string{"109.120.137.190"}

	// Список исключений из живого отказа: полный туннель минус 10/8, 100/8, 172/8. Литерального
	// 0.0.0.0/0 в нём нет, но 104.0.0.0/5 накрывает адрес хаба — обход обязан ставиться.
	exclude := []string{
		"0.0.0.0/5", "8.0.0.0/7", "11.0.0.0/8", "12.0.0.0/6", "16.0.0.0/4", "32.0.0.0/3",
		"64.0.0.0/3", "96.0.0.0/6", "101.0.0.0/8", "102.0.0.0/7", "104.0.0.0/5", "112.0.0.0/4",
		"128.0.0.0/3", "160.0.0.0/5", "168.0.0.0/6", "173.0.0.0/8", "174.0.0.0/7", "176.0.0.0/4",
		"192.0.0.0/2",
	}
	if !endpointCovered(exclude, hub) {
		t.Fatal("список исключений накрывает адрес хаба (104.0.0.0/5 ⊇ 109.x) — обход обязан требоваться")
	}

	// Раздельный туннель на саму звезду адрес хаба НЕ накрывает — обход не нужен.
	if endpointCovered([]string{"10.9.0.0/24"}, hub) {
		t.Fatal("10.9.0.0/24 не содержит 109.120.137.190 — обход не должен требоваться")
	}

	// Литеральный полный туннель накрывает всё.
	if !endpointCovered([]string{"0.0.0.0/0"}, hub) {
		t.Fatal("0.0.0.0/0 содержит любой адрес")
	}

	// Без адреса хаба решать нечего.
	if endpointCovered([]string{"0.0.0.0/0"}, nil) {
		t.Fatal("без конечной точки обход не требуется")
	}

	// Исключение, которое НЕ накрывает хаб: если бы 104/5 в списке не было, обход не нужен.
	noHub := []string{"0.0.0.0/5", "8.0.0.0/7", "10.0.0.0/8"}
	if endpointCovered(noHub, hub) {
		t.Fatal("ни один из этих префиксов не содержит 109.x")
	}
}

// Маршрут по умолчанию не раскладывается вместе с остальными: его ставит сторож после
// доказательства пересылки (I-275).
func TestSplitDefaultОтделяетНулевойПрефикс(t *testing.T) {
	rest, full := splitDefault([]string{"10.0.0.0/8", " 0.0.0.0/0 ", "::/0", "192.168.0.0/16"})
	if !full {
		t.Fatal("0.0.0.0/0 не распознан как полный туннель")
	}
	if len(rest) != 3 || rest[0] != "10.0.0.0/8" || rest[1] != "::/0" || rest[2] != "192.168.0.0/16" {
		t.Fatalf("остаток %v: /0 IPv4 обязан уйти, прочее — остаться", rest)
	}
	if rest, full := splitDefault([]string{"10.0.0.0/8"}); full || len(rest) != 1 {
		t.Fatalf("без /0 полного туннеля нет: %v %v", rest, full)
	}
}

func TestParseRouteGet(t *testing.T) {
	for _, c := range []struct{ in, via, dev string }{
		{"203.0.113.5 via 192.168.1.1 dev eth0 src 192.168.1.50 uid 1000\n    cache\n", "192.168.1.1", "eth0"},
		{"203.0.113.5 dev wlan0 src 10.0.0.7 uid 0\n", "", "wlan0"},
		{"", "", ""},
	} {
		via, dev := parseRouteGet(c.in)
		if via != c.via || dev != c.dev {
			t.Errorf("%q: via=%q dev=%q, ждали %q %q", c.in, via, dev, c.via, c.dev)
		}
	}
}
