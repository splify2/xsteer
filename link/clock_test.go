package link

import "testing"

// Таймеры пути идут по монотонным часам: значение отсчитывается от запуска, а не от эпохи Unix,
// которую двигает синхронизация времени (стенные часы дали бы здесь ~1.7e12).
func TestЧасыПутиМонотонные(t *testing.T) {
	a := nowMS()
	if a < 1 || a > 1<<40 {
		t.Fatalf("nowMS=%d: похоже на стенные часы", a)
	}
	if b := nowMS(); b < a {
		t.Fatalf("время пошло назад: %d < %d", b, a)
	}
}
